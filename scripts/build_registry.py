#!/usr/bin/env python3
"""Maintainer tool: regenerate skills/ui-template-apply/library/registry.json from the library files.

Dependencies are derived from import specifiers, so the registry cannot drift from the code.
  build_registry.py [--check]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "skills/ui-template-apply/library"
IMPORT = re.compile(r'''(?:from|import)\s+["']([^"']+)["']''')
VERSIONS = {  # pinned majors verified together with shadcn@4.21.4 radix-nova
    "@fontsource-variable/geist": "^5", "@tanstack/react-table": "^8", "@tanstack/react-virtual": "^3",
    "class-variance-authority": "^0.7", "cmdk": "^1", "cn": "^0.4", "lucide-react": "^1", "radix-ui": "^1",
    "react-markdown": "^10", "react-router": "^8", "remark-gfm": "^4", "sonner": "^2", "tw-animate-css": "^1",
    "shadcn": "4.21.4",
}
BASE_DEPS = ["@fontsource-variable/geist", "tw-animate-css", "shadcn", "cn"]
DEV_DEPS = ["tailwindcss@^4", "@tailwindcss/vite@^4", "eslint@^9", "typescript-eslint@^8", "@types/node@^24"]


def item_for(path: Path) -> tuple[str, str]:
    rel = path.relative_to(LIB).as_posix()
    if rel.startswith("shadcn/ui/"):
        return "ui/" + path.stem, "src/components/ui/" + path.name
    if rel.startswith("shadcn/hooks/"):
        return "hooks/" + path.stem, "src/hooks/" + path.name
    if rel == "shadcn/lib/utils.ts":
        return "lib/utils", "src/lib/utils.ts"
    if rel == "blocks/vocab.ts":
        return "vocab", "src/lib/vocab.ts"
    if rel.startswith("blocks/"):
        return "blocks/" + path.stem, "src/components/blocks/" + path.name
    if rel.startswith("lint/"):
        return "lint/" + path.stem, "eslint/" + path.name
    raise ValueError(rel)


def spec_to_item(spec: str) -> str | None:
    for prefix, kind in (("@/components/ui/", "ui/"), ("@/components/blocks/", "blocks/"), ("@/hooks/", "hooks/")):
        if spec.startswith(prefix):
            return kind + spec[len(prefix):]
    return {"@/lib/vocab": "vocab", "@/lib/utils": "lib/utils"}.get(spec)


def npm_name(spec: str) -> str | None:
    if spec.startswith((".", "@/")) or spec in ("react", "react-dom") or spec.startswith("react/"):
        return None
    parts = spec.split("/")
    return "/".join(parts[:2]) if spec.startswith("@") else parts[0]


def build() -> dict:
    items = []
    paths = sorted(p for p in LIB.rglob("*") if p.suffix in (".ts", ".tsx", ".mjs") and "node_modules" not in p.parts)
    for path in paths:
        name, target = item_for(path)
        text = path.read_text(encoding="utf-8")
        specs = IMPORT.findall(text)
        reg = sorted({i for s in specs if (i := spec_to_item(s)) is not None and i != name})
        npm = sorted({f"{n}@{VERSIONS.get(n, 'latest')}" for s in specs if (n := npm_name(s)) is not None and n not in ("eslint",)})
        items.append({
            "name": name,
            "files": [{"path": path.relative_to(LIB).as_posix(), "target": target, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}],
            "dependencies": npm,
            "registryDependencies": reg,
        })
    return {
        "$comment": "generated by scripts/build_registry.py; do not edit",
        "base": {"cli": "shadcn@4.21.4", "base": "radix", "style": "nova"},
        "theme_target": "src/styles/theme.css",
        "baseDependencies": [f"{n}@{VERSIONS[n]}" for n in BASE_DEPS],
        "devDependencies": DEV_DEPS,
        "items": items,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    target = LIB / "registry.json"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print("registry.json is stale; run scripts/build_registry.py", file=sys.stderr)
            return 1
        print("registry.json up to date")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
