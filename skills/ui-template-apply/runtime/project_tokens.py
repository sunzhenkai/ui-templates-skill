#!/usr/bin/env python3
"""Token Projection: Active Instance tokens -> CSS custom properties (generated, never hand-edited).

Deterministic, framework-neutral naming so every implementation projects the same way:

  color.<k>            -> --color-<k>
  radius.<k>           -> --radius-<k>
  shadow.<k>           -> --shadow-<k>
  font.family.<k>      -> --font-<k>
  font.weight.<k>      -> --font-weight-<k>
  typography.<k>       -> --text-<k>, --text-<k>--line-height[, --text-<k>--font-weight]
  size.<a>.<b>         -> --spacing-<a>-<b>         (size group prefix dropped)
  space.<k>            -> --spacing-<k>; numeric keys become --spacing-space-<k>
                          (never shadow the framework's numeric spacing scale)
  icon.size.default    -> --spacing-icon ; icon.size.<k> -> --spacing-icon-<k>
  icon.stroke-width    -> --icon-stroke-width ; icon.library is reported, not projected
  other groups         -> --<group>-<path>

Numbers with a unit are emitted as <value><unit> (unitless/ratio bare). Theme variants
(tokens.themes.variants.<name>) are emitted as a block under the variant selector
(default ".<name>") that redeclares the same variable names, plus ``color-scheme``.

Formats: ``tailwind4`` wraps base tokens in ``@theme static { }`` (utilities such as
bg-<color>, h-<size>, text-<step>, rounded-<radius>, shadow-<k>, size-icon resolve to the
tokens); ``css`` uses ``:root { }``.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

import yaml


def _records(node: Any, prefix: str = "") -> dict[str, dict[str, Any]]:
    if isinstance(node, dict) and "value" in node and "origin" in node:
        return {prefix: node}
    out: dict[str, dict[str, Any]] = {}
    if isinstance(node, dict):
        for key, child in node.items():
            out.update(_records(child, f"{prefix}.{key}" if prefix else str(key)))
    return out


def css_value(record: dict[str, Any]) -> str:
    value, unit = record["value"], record.get("unit")
    if isinstance(value, (int, float)) and not isinstance(value, bool) and unit and unit not in ("unitless", "ratio"):
        return f"{value}{unit}"
    return str(value)


def variable_names(path: str, record: dict[str, Any]) -> list[tuple[str, str]]:
    group, _, rest = path.partition(".")
    dash = rest.replace(".", "-")
    if group == "color":
        return [(f"--color-{dash}", css_value(record))]
    if group in ("radius", "shadow"):
        return [(f"--{group}-{dash}", css_value(record))]
    if group == "font":
        kind, _, key = rest.partition(".")
        if kind == "family":
            return [(f"--font-{key.replace('.', '-')}", css_value(record))]
        if kind == "weight":
            return [(f"--font-weight-{key.replace('.', '-')}", css_value(record))]
        return [(f"--font-{dash}", css_value(record))]
    if group == "typography":
        out = [(f"--text-{dash}", css_value(record))]
        if record.get("line_height") is not None:
            lh_unit = record.get("line_height_unit", "px")
            out.append((f"--text-{dash}--line-height", f"{record['line_height']}{'' if lh_unit == 'unitless' else lh_unit}"))
        if record.get("font_weight") is not None:
            out.append((f"--text-{dash}--font-weight", str(record["font_weight"])))
        return out
    if group == "size":
        return [(f"--spacing-{dash}", css_value(record))]
    if group == "space":
        return [(f"--spacing-{'space-' + dash if dash[:1].isdigit() else dash}", css_value(record))]
    if group == "icon":
        if rest == "library":
            return []
        if rest == "stroke-width":
            return [("--icon-stroke-width", css_value(record))]
        if rest.startswith("size."):
            key = rest.removeprefix("size.")
            return [("--spacing-icon" if key == "default" else f"--spacing-icon-{key.replace('.', '-')}", css_value(record))]
    return [(f"--{group}-{dash}", css_value(record))]


def project(tokens_doc: dict[str, Any], fmt: str = "tailwind4") -> str:
    base = _records(tokens_doc.get("tokens", {}))
    lines = ["/* GENERATED by project_tokens.py from the Active Instance tokens layer. Do not edit. */"]
    lines.append("@theme static {" if fmt == "tailwind4" else ":root {")
    seen: dict[str, tuple[str, str]] = {}
    for path in base:
        for name, value in variable_names(path, base[path]):
            if name in seen:
                if seen[name][1] != value:
                    raise SystemExit(f"PROJECTION_COLLISION: {name} from {seen[name][0]}={seen[name][1]} and {path}={value}")
                continue
            seen[name] = (path, value)
            lines.append(f"  {name}: {value};")
    lines.append("}")
    if fmt == "tailwind4":
        stroke = [v for p, r in base.items() if p == "icon.stroke-width" for _, v in variable_names(p, r)]
        if stroke:  # non-theme variable must also exist at runtime
            lines.append(f":root {{ --icon-stroke-width: {stroke[0]}; }}")
    themes = tokens_doc.get("themes") or {}
    for name, variant in (themes.get("variants") or {}).items():
        selector = variant.get("selector") or f".{name}"
        lines.append(f"{selector} {{")
        if name in ("dark", "light"):
            lines.append(f"  color-scheme: {name};")
        for path, record in (variant.get("overrides") or {}).items():
            for var, value in variable_names(path, record):
                lines.append(f"  {var}: {value};")
        lines.append("}")
    library = base.get("icon.library")
    if library:
        lines.append(f"/* icon.library = {library['value']} */")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--instance", required=True, type=Path, help="Active Instance root (.ui-template-design)")
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--format", choices=["tailwind4", "css"], default="tailwind4")
    parser.add_argument("--check", action="store_true", help="fail if --out differs from a fresh projection")
    args = parser.parse_args(argv)
    manifest = yaml.safe_load((args.instance / "design-system.yaml").read_text())
    tokens_doc = yaml.safe_load((args.instance / manifest["layers"]["tokens"]).read_text())
    css = project(tokens_doc, args.format)
    digest = hashlib.sha256(css.encode()).hexdigest()
    if args.check:
        same = args.out.is_file() and args.out.read_text() == css
        print(json.dumps({"projection": str(args.out), "up_to_date": same}))
        return 0 if same else 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(css)
    print(json.dumps({"projection": str(args.out), "sha256": digest}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
